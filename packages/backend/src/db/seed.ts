export function seedDatabase(store: SqliteStore): void {
  const existing = store.queryOne<{ count: number }>('SELECT COUNT(*) as count FROM couriers');
  if (existing && Number(existing.count) > 0) {
    return;
  }

  store.executeBatch((db) => {
    const insertCourier = db.prepare(`
      INSERT INTO couriers (
        id, name, rating, completed_deliveries, vehicle_model, vehicle_class,
        license_plate, phone, bio, current_address,
        trunk_length_cm, trunk_width_cm, trunk_height_cm,
        trunk_max_weight_kg, trunk_volume_liters, current_hub, destination_hub,
        available_from, price_per_km_pln, status, avatar_initials, map_x, map_y
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    `);

    for (const c of SEED_COURIERS) {
      insertCourier.run([
        c.id,
        c.name,
        c.rating,
        c.completedDeliveries,
        c.vehicleModel,
        c.vehicleClass,
        c.licensePlate,
        c.phone,
        c.bio,
        c.currentAddress,
        c.trunk.lengthCm,
        c.trunk.widthCm,
        c.trunk.heightCm,
        c.trunk.maxWeightKg,
        c.trunk.volumeLiters,
        c.currentHub,
        c.destinationHub,
        c.availableFrom,
        c.pricePerKmPln,
        c.status,
        c.avatarInitials,
        c.mapX,
        c.mapY,
      ]);
    }
    insertCourier.free();

    const insertShipment = db.prepare(`
      INSERT INTO shipments (
        id, title, business_name, direction, pickup_hub, pickup_address,
        pickup_map_x, pickup_map_y, dropoff_hub, dropoff_address,
        dropoff_map_x, dropoff_map_y, distance_km, cargo_description,
        estimate_json, status, assigned_courier_id, created_at
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    `);

    for (const s of SEED_SHIPMENTS) {
      insertShipment.run([
        s.id,
        s.title,
        s.businessName,
        s.direction,
        s.pickupHub,
        s.pickupAddress,
        s.pickupMapX ?? null,
        s.pickupMapY ?? null,
        s.dropoffHub,
        s.dropoffAddress,
        s.dropoffMapX ?? null,
        s.dropoffMapY ?? null,
        s.distanceKm,
        s.cargoDescription,
        JSON.stringify(s.estimate),
        s.status,
        s.assignedCourierId,
        s.createdAt,
      ]);
    }
    insertShipment.free();

    const insertMessage = db.prepare(`
      INSERT INTO courier_messages (
        id, courier_id, sender, sender_name, text, created_at
      ) VALUES (?, ?, ?, ?, ?, ?)
    `);

    for (const msg of SEED_COURIER_MESSAGES) {
      insertMessage.run([
        msg.id,
        msg.courierId,
        msg.sender,
        msg.senderName,
        msg.text,
        msg.createdAt,
      ]);
    }
    insertMessage.free();

    const insertMetric = db.prepare(`
      INSERT INTO monthly_metrics (
        month_index, month, outbound_pln, inbound_pln, outbound_count, inbound_count, co2_saved_kg
      ) VALUES (?, ?, ?, ?, ?, ?, ?)
    `);

    for (const m of SEED_MONTHLY_METRICS) {
      insertMetric.run([
        m.monthIndex,
        m.month,
        m.outboundPln,
        m.inboundPln,
        m.outboundCount,
        m.inboundCount,
        m.co2SavedKg,
      ]);
    }
    insertMetric.free();
  });
}
